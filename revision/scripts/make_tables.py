def stress_expected(var):
    return 1 if var.startswith("heur_") else (3 if var in STRESS_CORE else 2)


def stress_cells(var, first_quarter=False):
    r = R["stress"].get(var)
    k = 8 if first_quarter else 7
    if not r:
        return [TBD] * k
    m, lo, hi = r["mean"], r["min"], r["max"]
    n = len(r["seeds"])
    lam = (f"{m['lam_ov_end']:.0f}" if ok(m.get("lam_ov_end")) else "--")
    # frozen-price rows have no dual update, hence no cap
    if not var.startswith("fixed_") and ok(m.get("at_cap_frac")) and m["at_cap_frac"] > 0:
        lam += f"$^\\dagger$"
    cells = [str(n), f(m["etr"], 1), f(m["sat"], 3), f(m["edel"], 1), f(m["ov"], 2),
             f(m["p_ov"], 0, pct=True)]
    if first_quarter:
        cells.append("--" if var.startswith("heur_") else f(m.get("true_ov_first_quarter"), 2))
    cells.append(lam)
    if n < stress_expected(var):
        cells = [c if c.startswith(r"\tbd") else r"\tbd{" + c + "}" for c in cells]
    return cells


