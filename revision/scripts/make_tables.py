"""Write the LaTeX tables of the revised manuscript and its supplement from the
results on disk (revision/analysis/{submitted_stats,results}.json). Any value
not yet computed is printed as \\tbd{--}, so rerunning this script after the
campaign fills every table without touching the text.

    python scripts/collect_results.py && python scripts/make_tables.py
"""
import json, os
import numpy as np

REV = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(REV)
TAB = os.path.join(REPO, "IEEE TTE", "tables")
os.makedirs(TAB, exist_ok=True)
S = json.load(open(os.path.join(REV, "analysis", "submitted_stats.json")))
R = json.load(open(os.path.join(REV, "analysis", "results.json")))
PEM = json.load(open(os.path.join(REPO, "results", "cityNL", "per_episode_metrics.json")))
TBD = r"\tbd{--}"
ORDER = ["CAFAP", "Round-Robin", "DDPG-PST", "PPO-PST", "CPO", "Fixed-price SAC", "TC-CPL"]


def ok(x):
    return x is not None and not (isinstance(x, float) and (np.isnan(x) or np.isinf(x)))


def f(x, nd=0, pct=False, thou=False):
    if not ok(x):
        return TBD
    if pct:
        x = 100 * x
    if thou:
        return f"{x:,.{nd}f}".replace(",", "{,}")
    return f"{x:.{nd}f}"


def interim(lab, e, cell):
    """cityNL extended metrics come from the re-evaluated checkpoints; a row with
    fewer seeds than the controller has is interim and printed with \\tbd."""
    want = 1 if lab in ("Round-Robin", "CAFAP") else 5
    if cell.startswith(r"\tbd") or (e.get("seeds") or 0) >= want:
        return cell
    return r"\tbd{" + cell + "}"


def write(name, body):
    with open(os.path.join(TAB, name), "w") as fh:
        fh.write("% generated by revision/scripts/make_tables.py -- do not edit by hand\n" + body)


