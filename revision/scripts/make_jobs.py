"""Write the job lists of the revision campaign (October 2026, revised protocol).

    python scripts/make_jobs.py

1. revision/stress_tasks.txt -- the PublicPST-S experiments for the cluster array
   revision/stress_sweep.sh, one task per line: VARIANT SEED [shield]. Each task trains
   the variant (CAMPAIGN settings of variants.py), evaluates it on the 100 shared days
   and, when marked "shield", also evaluates it with the headroom projection.
2. revision/jobs.json -- the evaluations that run on one machine AFTER the cluster
   results are unpacked (scripts/campaign.py jobs.json N): cityNL and PublicPST_S
   re-evaluation of the main checkpoints with per-interval / per-vehicle records,
   the cityNL headroom projection, observation perturbations and held-out days.
"""
import json, os, sys

REV = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REV)
from variants import VARIANTS, CAMPAIGN

PY = sys.executable
# 3 seeds: the method, its ablations and the two settings changed in the revision
CORE = ["tccpl", "fixed_100_50", "fixed_500_5", "tau_2", "lmax_2000",
        "no_demos", "no_residual", "no_gridblock", "flat_encoder", "inc_cafap",
        "rho_0p25", "no_load_aware"]
# 2 seeds: sensitivity of the dual controller and of the fixed prices
SENS = ["fixed_10_5", "fixed_10_50", "fixed_100_5", "fixed_500_50", "fixed_2000_50",
        "lmax_100", "tau_0p5", "pi_kp0", "pi_ki0p5", "pi_ki8", "no_m2",
        "inc_cafap_rho0p25", "margin0", "pi_al"]
CORE_SEEDS, SENS_SEEDS = [42, 43, 44], [42, 43]
SHIELD = {"heur_RR", "heur_CAFAP", "tccpl", "fixed_100_50", "no_residual", "tau_2"}
PERTURB = ["status_flip:0.1", "status_flip:0.3", "status_hide:0.1", "status_hide:0.3",
           "status_delay:1", "nev_bias:0.2", "nev_bias:-0.2", "rating_bias:0.05",
           "rating_bias:-0.05", "dr_notice:0", "dr_notice:2", "nev_persist:1"]
LEARNERS = ("tccpl", "fixedpenalty", "ddpg_pst", "ppo_pst", "cpo_pst")
SEEDS = (42, 43, 44, 45, 46)

for v in CORE + SENS:
    assert v in VARIANTS, f"unknown variant {v}"

# ── 1. cluster: PublicPST-S tasks ────────────────────────────────────────────
tasks = [("heur_RR", 0), ("heur_CAFAP", 0)]
tasks += [(v, s) for s in CORE_SEEDS for v in CORE]
tasks += [(v, s) for s in SENS_SEEDS for v in SENS]
with open(os.path.join(REV, "stress_tasks.txt"), "w") as fh:
    fh.write("# VARIANT SEED [shield] -- generated by scripts/make_jobs.py; "
             f"settings: {CAMPAIGN}\n")
    for v, s in tasks:
        fh.write(f"{v} {s}{' shield' if v in SHIELD else ''}\n")


# ── 2. after the cluster: evaluations on one machine ─────────────────────────
def ev_job(label, s, scen="cityNL", pert=None, days=100, shield=False, offset=500):
    tag = ("" if pert is None else "_" + pert.replace(":", "")) + ("_shield" if shield else "")
    out = f"runs/{scen}_eval/{label}_s{s}{tag}_n{days}" + ("" if offset == 500 else f"_o{offset}") + ".json"
    env = {"EXP_THREADS": 1, "EXP_SCEN": scen}
    if shield:
        env["EXP_SHIELD"] = 1
    return {"name": f"{scen}_{label}_s{s}{tag}_n{days}" + ("" if offset == 500 else f"_o{offset}"),
            "cmd": f"{PY} scripts/eval_citynl.py {label} {s}" + ("" if pert is None else f" {pert}")
                   + f" --days {days}" + ("" if offset == 500 else f" --offset {offset}"),
            # done only if the output was made from the checkpoint now in models/
            "done_if": out, "stamp": [scen, label, s], "env": env}


jobs = []
for scen in ("cityNL", "PublicPST_S"):
    jobs += [ev_job(l, s, scen) for l in LEARNERS for s in SEEDS]
    jobs += [ev_job(h, 0, scen) for h in ("RR", "CAFAP")]
jobs += [ev_job(l, s, shield=True) for l in ("tccpl", "fixedpenalty") for s in SEEDS]
jobs += [ev_job(h, 0, shield=True) for h in ("RR", "CAFAP")]
jobs += [ev_job(l, s, pert=p, days=50) for p in PERTURB for s in (42, 43, 44) for l in ("tccpl", "fixedpenalty")]
jobs += [ev_job(l, s, offset=5000) for l in ("tccpl", "fixedpenalty") for s in SEEDS]
jobs += [ev_job(h, 0, offset=5000) for h in ("RR", "CAFAP")]
json.dump(jobs, open(os.path.join(REV, "jobs.json"), "w"), indent=1)

print(f"stress_tasks.txt: {len(tasks)} cluster tasks ({len(CORE)} core variants x {len(CORE_SEEDS)} seeds, "
      f"{len(SENS)} sensitivity variants x {len(SENS_SEEDS)} seeds, 2 heuristics)")
print(f"jobs.json: {len(jobs)} evaluations for after the cluster")
